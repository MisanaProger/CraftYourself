//! Generated views. Every view reads the same items, so a status changed in
//! the data changes everywhere the item is shown (§5.9).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::metrics::{Progress, metrics, progress};
use crate::validate::dependency_cycles;
use crate::{Entry, Item, Kind, LinkType, Roadmap, Status, anchor, criterion};

pub const SUMMARY_BEGIN: &str = "<!-- roadmap-summary:begin (generated by `cargo run -p est-roadmap -- render`; do not edit) -->";
pub const SUMMARY_END: &str = "<!-- roadmap-summary:end -->";

fn header(source: &str) -> String {
    format!(
        "<!-- Generated by `cargo run -p est-roadmap -- render` from {source}. \
         Do not edit: change the data and render again. -->\n\n"
    )
}

fn pct(p: &Progress) -> String {
    match p.percent() {
        None => "—".into(),
        Some(v) if p.unestimated > 0 && p.unestimated == p.leaves - p.cancelled => {
            format!("{v} % (unestimated)")
        }
        Some(v) => format!("{v} %"),
    }
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn status_badge(s: Status) -> String {
    let icon = match s {
        Status::Done => "✅",
        Status::InProgress | Status::InReview => "◐",
        Status::Blocked => "⛔",
        Status::Deferred => "⏸",
        Status::Cancelled => "✖",
        Status::Ready => "▶",
        Status::Planned | Status::Proposed => "◯",
    };
    format!("{icon} {}", s.label())
}

/// Link to an item from a file in the views directory.
fn item_link(rm: &Roadmap, from_roadmap: &str, id: &str) -> String {
    match rm.get(id) {
        None => format!("`{id}`"),
        Some(e) if e.roadmap == from_roadmap => format!("[{id}](#{})", anchor(id)),
        Some(e) => format!("[{id}]({}.md#{})", e.roadmap, anchor(id)),
    }
}

fn item_ref(rm: &Roadmap, from_roadmap: &str, id: &str) -> String {
    match rm.get(id) {
        None => format!("`{id}`"),
        Some(e) => format!(
            "{} {} ({})",
            item_link(rm, from_roadmap, id),
            e.item.name,
            e.item.status.label()
        ),
    }
}

/// Repository path linked from `docs/roadmaps/` (two levels below the root).
fn repo_link(views_dir: &str, path: &str) -> String {
    let up = "../".repeat(views_dir.split('/').filter(|s| !s.is_empty()).count());
    format!("[`{path}`]({up}{path})")
}

/// Items of a roadmap in tree order with their depth.
fn tree<'a>(rm: &'a Roadmap, roadmap: &str) -> Vec<(&'a Entry, usize)> {
    let mine: Vec<&Entry> = rm.items.iter().filter(|e| e.roadmap == roadmap).collect();
    let ids: BTreeSet<&str> = mine.iter().map(|e| e.item.id.as_str()).collect();
    let mut out = Vec::new();
    let mut visited = BTreeSet::new();
    fn walk<'a>(
        rm: &'a Roadmap,
        e: &'a Entry,
        depth: usize,
        roadmap: &str,
        out: &mut Vec<(&'a Entry, usize)>,
        visited: &mut BTreeSet<&'a str>,
    ) {
        if !visited.insert(e.item.id.as_str()) {
            return;
        }
        out.push((e, depth));
        for c in rm.children(&e.item.id) {
            if c.roadmap == roadmap {
                walk(rm, c, depth + 1, roadmap, out, visited);
            }
        }
    }
    for e in &mine {
        let root = e.item.parent.as_deref().is_none_or(|p| !ids.contains(p));
        if root {
            walk(rm, e, 0, roadmap, &mut out, &mut visited);
        }
    }
    // anything left (parent loops) still shows up
    for e in &mine {
        if !visited.contains(e.item.id.as_str()) {
            out.push((e, 0));
        }
    }
    out
}

/// Links pointing at an item from other items, by type.
fn incoming<'a>(rm: &'a Roadmap, id: &str) -> BTreeMap<LinkType, Vec<&'a str>> {
    let mut m: BTreeMap<LinkType, Vec<&str>> = BTreeMap::new();
    for e in &rm.items {
        for t in LinkType::ALL {
            if e.item.links(t).iter().any(|x| x == id) {
                m.entry(t).or_default().push(e.item.id.as_str());
            }
        }
    }
    m
}

fn incoming_label(t: LinkType) -> &'static str {
    match t {
        LinkType::DependsOn => "Needed by",
        LinkType::Blocks => "Blocked by",
        LinkType::RelatedTo => "Related to (from)",
        LinkType::Implements => "Implemented by",
        LinkType::Validates => "Validated by",
        LinkType::Extends => "Extended by",
        LinkType::Replaces => "Replaced by",
    }
}

fn checklist(out: &mut String, title: &str, list: &[String]) {
    if list.is_empty() {
        return;
    }
    let _ = writeln!(out, "\n**{title}**\n");
    for c in list {
        match criterion(c) {
            Some((true, t)) => {
                let _ = writeln!(out, "- [x] {t}");
            }
            Some((false, t)) => {
                let _ = writeln!(out, "- [ ] {t}");
            }
            None => {
                let _ = writeln!(out, "- {c}");
            }
        }
    }
}

fn item_section(rm: &Roadmap, e: &Entry, depth: usize, out: &mut String) {
    let it: &Item = &e.item;
    let views = rm.config.views_dir.as_str();
    let hashes = "#".repeat((3 + depth).min(6));
    let _ = writeln!(
        out,
        "\n{hashes} <a id=\"{}\"></a>{} · {}\n",
        anchor(&it.id),
        it.id,
        it.name
    );
    let mut meta = vec![format!("**{}**", it.kind.label()), status_badge(it.status)];
    if let Some(p) = it.priority {
        meta.push(format!("{p:?}"));
    }
    if let Some(r) = &it.release {
        meta.push(format!("release {}", item_link(rm, &e.roadmap, r)));
    }
    if let Some(v) = &it.version {
        meta.push(format!("version {v}"));
    }
    if let Some(o) = rm.owner(it) {
        meta.push(format!("owner {o}"));
    }
    if let Some(r) = it.risk {
        meta.push(format!("risk {r:?}").to_lowercase());
    }
    match (it.estimate_days, it.actual_days) {
        (Some(est), Some(act)) => meta.push(format!("estimate {est} d / actual {act} d")),
        (Some(est), None) => meta.push(format!("estimate {est} d")),
        (None, Some(act)) => meta.push(format!("actual {act} d")),
        _ => {}
    }
    if let Some(d) = &it.due {
        meta.push(format!("due {d}"));
    }
    if rm.children(&it.id).next().is_some() {
        meta.push(format!("progress {}", pct(&progress(rm, &it.id))));
    }
    if !it.tags.is_empty() {
        meta.push(
            it.tags
                .iter()
                .map(|t| format!("`{t}`"))
                .collect::<Vec<_>>()
                .join(" "),
        );
    }
    let _ = writeln!(out, "{}", meta.join(" · "));
    if let Some(d) = &it.description {
        let _ = writeln!(out, "\n{}", d.trim());
    }
    if let Some(r) = &it.status_reason {
        let _ = writeln!(out, "\n> **Status reason:** {}", r.trim());
    }
    let mut links = Vec::new();
    if let Some(p) = &it.parent {
        links.push(format!("- **Parent:** {}", item_ref(rm, &e.roadmap, p)));
    }
    for t in LinkType::ALL {
        let l = it.links(t);
        if !l.is_empty() {
            links.push(format!(
                "- **{}:** {}",
                t.label(),
                l.iter()
                    .map(|x| item_ref(rm, &e.roadmap, x))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }
    for (t, from) in incoming(rm, &it.id) {
        links.push(format!(
            "- **{}:** {}",
            incoming_label(t),
            from.iter()
                .map(|x| item_ref(rm, &e.roadmap, x))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    if !links.is_empty() {
        let _ = writeln!(out, "\n{}", links.join("\n"));
    }
    if let Some(h) = &it.hypothesis {
        let _ = writeln!(out, "\n**Hypothesis:** {}", h.trim());
    }
    if let Some(a) = &it.accept_if {
        let _ = writeln!(out, "\n**Accept if:** {}", a.trim());
    }
    if let Some(r) = &it.reject_if {
        let _ = writeln!(out, "\n**Reject if:** {}", r.trim());
    }
    if let Some(r) = &it.result {
        let _ = writeln!(out, "\n**Result:** {}", r.trim());
    }
    checklist(out, "Acceptance criteria", &it.acceptance);
    checklist(
        out,
        "Definition of Done (in addition to the project's)",
        &it.done_when,
    );
    if !it.components.is_empty() {
        let _ = writeln!(
            out,
            "\n**Components:** {}",
            it.components
                .iter()
                .map(|c| repo_link(views, c))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    if !it.docs.is_empty() {
        let _ = writeln!(
            out,
            "\n**Documentation:** {}",
            it.docs
                .iter()
                .map(|c| repo_link(views, c))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    if let Some(s) = &it.source {
        let _ = writeln!(out, "\n**Source:** {s}");
    }
    if it.kind == Kind::Release {
        let scope: Vec<&Entry> = rm
            .items
            .iter()
            .filter(|x| x.item.release.as_deref() == Some(it.id.as_str()))
            .collect();
        if !scope.is_empty() {
            let _ = writeln!(
                out,
                "\n| Scope | Name | Status | Priority | Progress |\n|---|---|---|---|---|"
            );
            for x in scope {
                let _ = writeln!(
                    out,
                    "| {} | {} | {} | {} | {} |",
                    item_link(rm, &e.roadmap, &x.item.id),
                    cell(&x.item.name),
                    status_badge(x.item.status),
                    x.item
                        .priority
                        .map(|p| format!("{p:?}"))
                        .unwrap_or_default(),
                    pct(&progress(rm, &x.item.id))
                );
            }
        }
    }
    if !it.changes.is_empty() {
        let _ = writeln!(out, "\n**Changes**\n");
        for c in &it.changes {
            let mut line = format!(
                "- {} — {} *Reason:* {}",
                c.date,
                c.summary.trim(),
                c.reason.trim()
            );
            if let Some(i) = &c.impact {
                let _ = write!(line, " *Impact:* {}", i.trim());
            }
            if let Some(d) = &c.decision {
                let _ = write!(line, " *Decision:* {}", repo_link(views, d));
            }
            let _ = writeln!(out, "{line}");
        }
    }
}

fn nav(rm: &Roadmap, current: &str) -> String {
    let mut parts: Vec<String> = rm
        .config
        .roadmaps
        .iter()
        .map(|r| {
            if r.id == current {
                format!("**{}**", r.title)
            } else {
                format!("[{}]({}.md)", r.title, r.id)
            }
        })
        .collect();
    for (id, title) in [("dependencies", "Dependencies"), ("metrics", "Metrics")] {
        parts.push(if id == current {
            format!("**{title}**")
        } else {
            format!("[{title}]({id}.md)")
        });
    }
    let up = "../".repeat(rm.config.views_dir.split('/').count());
    format!(
        "[↑ {}]({up}{}) · {}\n",
        rm.config.summary_file,
        rm.config.summary_file,
        parts.join(" · ")
    )
}

/// The view of one roadmap.
pub fn roadmap_view(rm: &Roadmap, roadmap: &str) -> String {
    let Some(def) = rm.roadmap(roadmap) else {
        return String::new();
    };
    let views = rm.config.views_dir.as_str();
    let mut out = header(&format!("roadmap/{}", def.file));
    let _ = writeln!(out, "# {}\n", def.title);
    let _ = writeln!(out, "{}", nav(rm, roadmap));
    let _ = writeln!(out, "{}\n", def.description.trim());
    let _ = writeln!(
        out,
        "Data: {} · prefix `{}` · rules: {}",
        repo_link(views, &format!("roadmap/{}", def.file)),
        def.prefix,
        repo_link(views, "docs/roadmap-management.md")
    );
    let items = tree(rm, roadmap);
    if items.is_empty() {
        let _ = writeln!(out, "\nNo items yet.");
        return out;
    }
    let _ = writeln!(
        out,
        "\n## Overview\n\n| ID | Name | Kind | Status | Priority | Release | Progress |\n|---|---|---|---|---|---|---|"
    );
    for (e, depth) in &items {
        let it = &e.item;
        let _ = writeln!(
            out,
            "| {} | {}{} | {} | {} | {} | {} | {} |",
            item_link(rm, roadmap, &it.id),
            "&nbsp;&nbsp;".repeat(*depth),
            cell(&it.name),
            it.kind.label(),
            status_badge(it.status),
            it.priority.map(|p| format!("{p:?}")).unwrap_or_default(),
            it.release
                .as_deref()
                .map(|r| item_link(rm, roadmap, r))
                .unwrap_or_default(),
            pct(&progress(rm, &it.id))
        );
    }
    let _ = writeln!(out, "\n## Items");
    for (e, depth) in &items {
        item_section(rm, e, *depth, &mut out);
    }
    out
}

fn node(id: &str) -> String {
    id.replace('-', "_")
}

/// Dependency edges `(dependency, dependent)`; `all` includes closed items.
pub fn dependency_edges(rm: &Roadmap, all: bool) -> Vec<(String, String)> {
    let mut edges = Vec::new();
    for e in &rm.items {
        for d in rm.dependencies(&e.item.id) {
            let open = |id: &str| rm.get(id).is_some_and(|x| !x.item.status.is_closed());
            if all || open(&e.item.id) || open(d) {
                edges.push((d.to_string(), e.item.id.clone()));
            }
        }
    }
    edges.sort();
    edges.dedup();
    edges
}

pub fn mermaid(rm: &Roadmap, all: bool) -> String {
    let edges = dependency_edges(rm, all);
    let nodes: BTreeSet<&str> = edges
        .iter()
        .flat_map(|(a, b)| [a.as_str(), b.as_str()])
        .collect();
    let mut out = String::from("flowchart LR\n");
    for n in &nodes {
        let label = rm
            .get(n)
            .map(|e| format!("{n}<br/>{}", e.item.name.replace('"', "'")))
            .unwrap_or_else(|| n.to_string());
        let class = rm
            .get(n)
            .map(|e| format!("{:?}", e.item.status).to_lowercase())
            .unwrap_or_default();
        let _ = writeln!(out, "  {}[\"{label}\"]:::{class}", node(n));
    }
    for (a, b) in &edges {
        let _ = writeln!(out, "  {} --> {}", node(a), node(b));
    }
    out.push_str(
        "  classDef done fill:#d4edda,stroke:#2e7d32,color:#1b3d1f\n  \
         classDef inprogress fill:#fff3cd,stroke:#b58900,color:#3d2f00\n  \
         classDef inreview fill:#fff3cd,stroke:#b58900,color:#3d2f00\n  \
         classDef blocked fill:#f8d7da,stroke:#c62828,color:#4a1015\n  \
         classDef ready fill:#dbeafe,stroke:#1d4ed8,color:#10204a\n  \
         classDef planned fill:#eef0f3,stroke:#6b7280,color:#1f2937\n  \
         classDef proposed fill:#ffffff,stroke:#9ca3af,color:#374151,stroke-dasharray:4 3\n  \
         classDef deferred fill:#eef0f3,stroke:#9ca3af,color:#6b7280\n  \
         classDef cancelled fill:#eef0f3,stroke:#9ca3af,color:#9ca3af\n",
    );
    out
}

pub fn dot(rm: &Roadmap, all: bool) -> String {
    let mut out = String::from("digraph roadmap {\n  rankdir=LR;\n  node [shape=box];\n");
    let edges = dependency_edges(rm, all);
    let nodes: BTreeSet<&str> = edges
        .iter()
        .flat_map(|(a, b)| [a.as_str(), b.as_str()])
        .collect();
    for n in nodes {
        let (name, st) = rm
            .get(n)
            .map(|e| (e.item.name.replace('"', "'"), e.item.status.label()))
            .unwrap_or_default();
        let _ = writeln!(out, "  \"{n}\" [label=\"{n}\\n{name}\\n[{st}]\"];");
    }
    for (a, b) in edges {
        let _ = writeln!(out, "  \"{a}\" -> \"{b}\";");
    }
    out.push_str("}\n");
    out
}

/// Open items ranked by how many open items depend on them, directly or
/// transitively.
pub fn bottlenecks(rm: &Roadmap) -> Vec<(String, usize)> {
    let mut dependents: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (a, b) in dependency_edges(rm, false) {
        dependents.entry(a).or_default().push(b);
    }
    let mut ranked: Vec<(String, usize)> = rm
        .items
        .iter()
        .filter(|e| !e.item.status.is_closed())
        .map(|e| {
            let mut seen = BTreeSet::new();
            let mut stack = vec![e.item.id.clone()];
            while let Some(n) = stack.pop() {
                for m in dependents.get(&n).into_iter().flatten() {
                    if rm.get(m).is_some_and(|x| !x.item.status.is_closed())
                        && seen.insert(m.clone())
                    {
                        stack.push(m.clone());
                    }
                }
            }
            (e.item.id.clone(), seen.len())
        })
        .filter(|(_, n)| *n > 0)
        .collect();
    ranked.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    ranked
}

pub fn dependencies_view(rm: &Roadmap) -> String {
    let mut out = header("roadmap/*.toml");
    let _ = writeln!(out, "# Dependencies\n");
    let _ = writeln!(out, "{}", nav(rm, "dependencies"));
    let _ = writeln!(
        out,
        "Arrows go from a dependency to the work that needs it (`depends_on`, and `blocks` read backwards). \
         Only edges that touch open work are drawn; `cargo run -p est-roadmap -- graph --all` prints every edge, \
         `--format dot` prints Graphviz.\n"
    );
    let _ = writeln!(out, "```mermaid\n{}```", mermaid(rm, false));
    let cycles = dependency_cycles(rm);
    let _ = writeln!(out, "\n## Cycles\n");
    if cycles.is_empty() {
        let _ = writeln!(out, "None.");
    } else {
        for c in cycles {
            let _ = writeln!(out, "- {} → {}", c.join(" → "), c[0]);
        }
    }
    let _ = writeln!(
        out,
        "\n## Bottlenecks\n\nOpen items that the most open work waits for, directly or transitively.\n\n| Item | Status | Open work waiting |\n|---|---|---|"
    );
    for (id, n) in bottlenecks(rm).into_iter().take(15) {
        let e = rm.get(&id).expect("ranked items exist");
        let _ = writeln!(
            out,
            "| {} {} | {} | {n} |",
            item_link(rm, "dependencies", &id),
            cell(&e.item.name),
            status_badge(e.item.status)
        );
    }
    out
}

pub fn metrics_view(rm: &Roadmap) -> String {
    let m = metrics(rm);
    let mut out = header("roadmap/*.toml");
    let _ = writeln!(out, "# Metrics\n");
    let _ = writeln!(out, "{}", nav(rm, "metrics"));
    let _ = writeln!(
        out,
        "Computed from the items' data. Progress is weighted by `estimate_days` and, for work in \
         progress, by the share of met acceptance criteria — never by the number of closed items \
         (see {}). Overdue items depend on today's date and are printed by \
         `cargo run -p est-roadmap -- metrics`.\n",
        repo_link(&rm.config.views_dir, "docs/roadmap-management.md#metrics")
    );
    let _ = writeln!(out, "## Items by status\n\n| Status | Items |\n|---|---|");
    for (s, n) in &m.by_status {
        let _ = writeln!(out, "| {} | {n} |", status_badge(*s));
    }
    let _ = writeln!(out, "| **Total** | **{}** |", m.items);
    let row = |out: &mut String, id: &str, p: &Progress| {
        let e = rm.get(id).expect("listed items exist");
        let _ = writeln!(
            out,
            "| [{id}]({}.md#{}) {} | {} | {} | {}/{} | {} | {} | {}/{} |",
            e.roadmap,
            anchor(id),
            cell(&e.item.name),
            status_badge(e.item.status),
            pct(p),
            p.done,
            p.leaves - p.cancelled,
            p.blocked,
            p.unestimated,
            p.criteria_met,
            p.criteria_total
        );
    };
    let table = "| Item | Status | Progress | Done leaves | Blocked | Unestimated | Criteria met |\n|---|---|---|---|---|---|---|";
    let _ = writeln!(out, "\n## Programs\n\n{table}");
    for (id, p) in &m.programs {
        row(&mut out, id, p);
    }
    let _ = writeln!(out, "\n## Epics\n\n{table}");
    for (id, p) in &m.epics {
        row(&mut out, id, p);
    }
    let _ = writeln!(
        out,
        "\n## Releases\n\n| Release | Version | Status | Due | Items | Progress | Blocked |\n|---|---|---|---|---|---|---|"
    );
    for r in &m.releases {
        let _ = writeln!(
            out,
            "| [{}](releases.md#{}) {} | {} | {} | {} | {} | {} | {} |",
            r.id,
            anchor(&r.id),
            cell(&r.name),
            r.version.clone().unwrap_or_default(),
            status_badge(r.status),
            r.due.clone().unwrap_or_else(|| "—".into()),
            r.items.len(),
            pct(&r.progress),
            r.progress.blocked
        );
    }
    let _ = writeln!(out, "\n## Acceptance criteria\n");
    let _ = writeln!(
        out,
        "Committed features, tasks and subtasks (Ready and later): {} of {} criteria met.",
        m.criteria_met, m.criteria_total
    );
    let _ = writeln!(out, "\n## Blocked\n");
    if m.blocked.is_empty() {
        let _ = writeln!(out, "None.");
    }
    for id in &m.blocked {
        let e = rm.get(id).expect("exists");
        let _ = writeln!(
            out,
            "- [{id}]({}.md#{}) {} — {}",
            e.roadmap,
            anchor(id),
            e.item.name,
            e.item
                .status_reason
                .clone()
                .unwrap_or_else(|| format!("waits for {}", rm.dependencies(id).join(", ")))
        );
    }
    let _ = writeln!(out, "\n## Technical debt\n");
    let _ = writeln!(
        out,
        "{} open items tagged `debt`, {} estimated days.\n",
        m.debt_open.len(),
        m.debt_days
    );
    for id in &m.debt_open {
        let e = rm.get(id).expect("exists");
        let _ = writeln!(
            out,
            "- [{id}]({}.md#{}) {} ({})",
            e.roadmap,
            anchor(id),
            e.item.name,
            e.item.status.label()
        );
    }
    let _ = writeln!(out, "\n## Planned versus actual effort\n");
    match m.effort.ratio() {
        None => {
            let _ = writeln!(
                out,
                "No finished leaf has both `estimate_days` and `actual_days` yet."
            );
        }
        Some(r) => {
            let _ = writeln!(
                out,
                "{} finished leaves: {:.1} days estimated, {:.1} actual (×{r:.2}).",
                m.effort.items, m.effort.estimated_days, m.effort.actual_days
            );
        }
    }
    let mut due: Vec<&Entry> = rm.items.iter().filter(|e| e.item.due.is_some()).collect();
    due.sort_by(|a, b| a.item.due.cmp(&b.item.due));
    let _ = writeln!(out, "\n## Due dates\n");
    if due.is_empty() {
        let _ = writeln!(out, "No item has a due date.");
    }
    for e in due {
        let _ = writeln!(
            out,
            "- {} — [{}]({}.md#{}) {} ({})",
            e.item.due.as_deref().unwrap_or_default(),
            e.item.id,
            e.roadmap,
            anchor(&e.item.id),
            e.item.name,
            e.item.status.label()
        );
    }
    out
}

/// The generated block of the entry point, markers included.
pub fn summary_block(rm: &Roadmap) -> String {
    let views = rm.config.views_dir.trim_end_matches('/');
    let mut out = format!("{SUMMARY_BEGIN}\n\n");
    let _ = writeln!(
        out,
        "| Roadmap | Items | Done | In progress | Ready / Planned / Proposed | Blocked | Progress |\n|---|---|---|---|---|---|---|"
    );
    for r in &rm.config.roadmaps {
        let items: Vec<&Entry> = rm.items.iter().filter(|e| e.roadmap == r.id).collect();
        let count = |f: &dyn Fn(Status) -> bool| items.iter().filter(|e| f(e.item.status)).count();
        let mut p = Progress::default();
        for e in &items {
            let top = e
                .item
                .parent
                .as_deref()
                .and_then(|x| rm.get(x))
                .is_none_or(|x| x.roadmap != r.id);
            if top && e.item.kind != Kind::Release {
                let q = progress(rm, &e.item.id);
                p.weight_total += q.weight_total;
                p.weight_done += q.weight_done;
                p.leaves += q.leaves;
                p.cancelled += q.cancelled;
                p.unestimated += q.unestimated;
            }
        }
        let _ = writeln!(
            out,
            "| [{}]({views}/{}.md) | {} | {} | {} | {} | {} | {} |",
            r.title,
            r.id,
            items.len(),
            count(&|s| s == Status::Done),
            count(&|s| matches!(s, Status::InProgress | Status::InReview)),
            count(&|s| matches!(s, Status::Ready | Status::Planned | Status::Proposed)),
            count(&|s| s == Status::Blocked),
            if r.id == "releases" {
                "—".into()
            } else {
                pct(&p)
            }
        );
    }
    let m = metrics(rm);
    if !m.releases.is_empty() {
        let _ = writeln!(
            out,
            "\n| Release | Version | Status | Progress |\n|---|---|---|---|"
        );
        for r in &m.releases {
            let _ = writeln!(
                out,
                "| [{}]({views}/releases.md#{}) {} | {} | {} | {} |",
                r.id,
                anchor(&r.id),
                cell(&r.name),
                r.version.clone().unwrap_or_default(),
                status_badge(r.status),
                pct(&r.progress)
            );
        }
    }
    let _ = writeln!(out, "\n{SUMMARY_END}");
    out
}

/// Replaces the generated block in the entry point. `None` when the
/// markers are missing.
pub fn splice_summary(existing: &str, block: &str) -> Option<String> {
    let start = existing.find(SUMMARY_BEGIN)?;
    let end_rel = existing[start..].find(SUMMARY_END)?;
    let end = start + end_rel + SUMMARY_END.len();
    // the block ends with the end marker and a newline
    let mut s = String::with_capacity(existing.len());
    s.push_str(&existing[..start]);
    s.push_str(block.trim_end_matches('\n'));
    s.push_str(&existing[end..]);
    Some(s)
}

/// Every generated view as `(path relative to the root, contents)`, except
/// the summary file (see [`summary_block`]).
pub fn views(rm: &Roadmap) -> Vec<(String, String)> {
    let dir = rm.config.views_dir.trim_end_matches('/');
    let mut out: Vec<(String, String)> = rm
        .config
        .roadmaps
        .iter()
        .map(|r| (format!("{dir}/{}.md", r.id), roadmap_view(rm, &r.id)))
        .collect();
    out.push((format!("{dir}/dependencies.md"), dependencies_view(rm)));
    out.push((format!("{dir}/metrics.md"), metrics_view(rm)));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splices_the_summary_block() {
        let doc = format!("# R\n\nintro\n\n{SUMMARY_BEGIN}\nold\n{SUMMARY_END}\n\nrest\n");
        let block = format!("{SUMMARY_BEGIN}\nnew\n{SUMMARY_END}\n");
        let s = splice_summary(&doc, &block).unwrap();
        assert_eq!(
            s,
            format!("# R\n\nintro\n\n{SUMMARY_BEGIN}\nnew\n{SUMMARY_END}\n\nrest\n")
        );
        assert_eq!(splice_summary(&s, &block).unwrap(), s);
        assert!(splice_summary("no markers", &block).is_none());
    }
}
